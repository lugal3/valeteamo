const assert=require('node:assert/strict');
(async()=>{
 const {START,RESCUE_SAVE_KEY,advanceRescue,parseRescue,openRescueHouseSave,openRescueEntrySave}=await import('../src/demo/progression.js');
 const {createHousePuzzle,puzzleEvent,canOpenBedroom,canRescue}=await import('../src/demo/house-puzzles.js');
 const unchanged=advanceRescue(START,'house');assert.equal(unchanged.house,false);
 let state=advanceRescue(START,'heart');assert.equal(state.phase,'heart');
 state=advanceRescue(state,'abduction');state=advanceRescue(state,'trail');state=advanceRescue(state,'house');
 assert.equal(state.phase,'house');assert.equal(state.rescued,false);
 for(const event of ['heart','abduction','trail','house'])assert.deepEqual(advanceRescue(state,event),state);
 const legacy=state;
 state=advanceRescue(state,'rescue');assert.equal(state.phase,'end');assert(state.rescued);
 for(const event of ['heart','abduction','trail','house','rescue'])assert.deepEqual(advanceRescue(state,event),state);
 assert.equal(parseRescue('broken').phase,'garden');
 assert.equal(parseRescue(JSON.stringify({...START,heart:false,abducted:true,house:true})).house,false);
 const storage=new Map([[RESCUE_SAVE_KEY,JSON.stringify(legacy)]]);
 Object.defineProperty(globalThis,'localStorage',{configurable:true,value:{
  getItem:key=>storage.get(key)??null,setItem:(key,value)=>storage.set(key,value)
 }});
 const current=openRescueHouseSave(),stale=openRescueHouseSave(),checkpoint={version:1,stage:'explore',picked:['key']};
 assert.equal(current.checkpoint,undefined,'A legacy house save has no interior checkpoint');
 current.save(checkpoint);
 assert.deepEqual(openRescueHouseSave().checkpoint,checkpoint);
 stale.save(null);stale.finish();
 assert.deepEqual(openRescueHouseSave().checkpoint,checkpoint,'A stale tab cannot erase or finish a newer save');
 current.save(null);
 assert.deepEqual(JSON.parse(storage.get(RESCUE_SAVE_KEY)),legacy);
 current.finish();current.save(checkpoint);
 assert.deepEqual(JSON.parse(storage.get(RESCUE_SAVE_KEY)),state,'Finishing drops the interior checkpoint');
 const publicStore=globalThis.localStorage;
 const completed=storage.get(RESCUE_SAVE_KEY);
 const completedLease=openRescueEntrySave(publicStore);
 assert.equal(completedLease.enter(),false,'completed save cannot be replaced by a new handoff');
 assert.equal(storage.get(RESCUE_SAVE_KEY),completed);
 storage.delete(RESCUE_SAVE_KEY);
 const first=openRescueEntrySave(publicStore),second=openRescueEntrySave(publicStore);
 assert.equal(first.enter(),true);
 const writer=first.openHouse();assert(writer);
 assert.equal(writer.save(checkpoint),true);
 assert.equal(second.enter(),false,'a concurrent prologue cannot overwrite a house checkpoint');
 assert.equal(second.openHouse(),undefined,'a stale handoff cannot adopt another tab checkpoint');
 const resume=openRescueEntrySave(publicStore);assert.equal(resume.enter(),true);
 assert.deepEqual(resume.openHouse().checkpoint,checkpoint,'resume preserves the entire interior checkpoint');
 assert.equal(writer.finish(),true);
 assert.equal(resume.openHouse(),undefined,'completed rescue invalidates older handoff');
 storage.delete(RESCUE_SAVE_KEY);
 assert.equal(resume.enter(),false,'reset invalidates an active handoff');
 delete globalThis.localStorage;
 let puzzle=createHousePuzzle();assert(!canOpenBedroom(puzzle));assert(!canRescue(puzzle));
 assert.equal(puzzleEvent(puzzle,'key').key,false,'The key still comes from the open drawer');
 puzzle=puzzleEvent(puzzle,'drawer');assert.equal(puzzle.drawer,true,'The drawer opens before reading the note');
 puzzle=puzzleEvent(puzzle,'key');assert.equal(puzzle.key,true);assert.equal(puzzle.note,false);
 assert(canOpenBedroom(puzzle));puzzle=puzzleEvent(puzzle,'door');assert(canRescue(puzzle));
 assert.equal(puzzle.symbol,false,'The mirror safe stays optional');
 puzzle=puzzleEvent(puzzle,'rescue');assert(puzzle.rescued);
 console.log('PASS: staged rescue, linked puzzles, lock requirements and corrupted-save recovery');
})().catch(e=>{console.error(e);process.exitCode=1});
