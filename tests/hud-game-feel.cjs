// ValeTeAmo V2 phase 11: contextual control instructions and visual safety.
const assert=require('node:assert/strict'),fs=require('node:fs');
(async()=>{
 const {rcControlHint,throwableHint,threatAccessibility,hopOffset,HOP_DURATION,HOP_COOLDOWN,advanceHop}=await import('../src/lab/hud-context.js');
 assert(rcControlHint(false).includes('W/S')&&rcControlHint(false).includes('Q:'));
 assert(rcControlHint(true).includes('Joystick')&&!rcControlHint(true).includes('W/S'));
 assert(rcControlHint(false,5).includes('Señuelo activo'));
 assert(rcControlHint(true,0,true).includes('Cerrar escotilla'));
 assert(rcControlHint(false,0,true).includes('Pulsa T'));
 assert(throwableHint(true).includes('Toca'));
 assert(throwableHint(false).includes('E o G: lanzar')&&!throwableHint(false).includes('V:'));
 assert(!throwableHint(true).includes('Suave'));
 assert.equal(hopOffset(0),0);
 assert.equal(hopOffset(HOP_DURATION),0);
 assert.equal(hopOffset(HOP_COOLDOWN),0);
 assert(Math.abs(hopOffset(HOP_DURATION/2)-.12)<1e-9);
 assert(hopOffset(HOP_DURATION/2,true)<hopOffset(HOP_DURATION/2));
 assert(HOP_COOLDOWN>HOP_DURATION);
 let hop=advanceHop(0,false,.1,true);
 assert.equal(hop.cancelled,false);
 hop=advanceHop(hop.age,hop.cancelled,.05,false);
 assert(hop.cancelled&&hop.age<HOP_COOLDOWN,'Crouching must not instantly re-arm a hop');
 hop=advanceHop(hop.age,hop.cancelled,0,true);
 assert(hop.cancelled&&hop.age<HOP_COOLDOWN,'Resuming pause cannot resurrect the animation');
 while(hop.age<HOP_COOLDOWN)hop=advanceHop(hop.age,hop.cancelled,.1,true);
 assert(hop.cancelled,'Cancelled animation stays cancelled until an intentional new hop');

 const {interactionIcon,feedbackIcon,createHaptics}=await import('../src/lab/hud-feedback.js');
 assert.equal(interactionIcon({kind:'door'}),'door');
 assert.equal(interactionIcon({kind:'key'}),'key');
 assert.equal(interactionIcon({kind:'emy-cat'}),'cat');
 assert.equal(interactionIcon({kind:'piano'},{throwing:true}),'throw');
 assert.equal(interactionIcon(null,{hidden:true}),'exit');
 assert(feedbackIcon('cat').includes('viewBox="0 0 24 24"'));
 let time=0,enabled=true;const pulses=[];
 const haptics=createHaptics({now:()=>time,enabled:()=>enabled,vibrate:p=>{pulses.push(p);return true;}});
 assert(haptics.pulse('pickup'));assert(!haptics.pulse('pickup'));assert(haptics.pulse('chase'));assert(!haptics.pulse('chase'));
 time=1200;assert(haptics.pulse('chase'));assert(haptics.pulse('capture'));enabled=false;assert(!haptics.pulse('capture'));
 assert.notDeepEqual(pulses[0],pulses[1]);haptics.stop();assert.equal(pulses.at(-1),0);
 assert(!createHaptics().pulse('key'),'Unsupported hardware is a harmless no-op');
 assert(threatAccessibility('chase').includes('Peligro'));
 assert(threatAccessibility('watch').includes('investigando'));
 assert(threatAccessibility('search').includes('Sin persecución'));
 const house=fs.readFileSync('src/lab/house.js','utf8');
 const css=fs.readFileSync('src/lab/house.css','utf8');
 for(const name of ['house-rc-hint','lab-interact'])assert(house.includes('id="'+name+'"'));
 assert(house.includes("rcControlHint(!desktop.matches,rc.noise,canTrapPursuer("));
 assert(house.includes("throwableHint(!desktop.matches)"));
 assert(house.includes("danger.setAttribute('aria-label',threatAccessibility("));
 assert(css.includes('.house-rc-hud[hidden]')&&css.includes('#lab3d #lab-interact:disabled'));
 assert(!house.includes('data-act="noise:lob"')&&!house.includes('data-act="noise:drop"'));
 const throwDispatch=house.indexOf("if(heldNoise&&!s.hidden&&!s.lying){runAction('noise:throw');return;}");
 const interactionDebounce=house.indexOf('if(now-lastInteraction<260)return');
 assert(throwDispatch>0&&interactionDebounce>throwDispatch,'A throw must not be swallowed by the previous pickup debounce');
 assert(house.includes('heldNoise=null;lastInteraction=performance.now();handAction=1;'));
 assert(house.includes('interactButton.disabled=!canInteract'));
 assert(house.includes('id="lab-hop"'));
 assert(house.includes('phone.close();$(\'lab-camera-settings\').open=false;bag();return;'),'Inventory replaces rather than stacks the phone settings');
 assert(house.includes('const canUseHotbar=()=>ready&&!heldNoise'),'Occupied hand cannot equip a second item');
 assert(/(?:const|let) visualEquipment=heldNoise\?'empty'/.test(house)&&house.includes('const normalEquip=!heldNoise'),'No floating second tool while throwing or transitioning');

 assert(house.includes('view={...view,y:view.y+hopOffset'));
 assert(css.includes('#lab3d #lab-hop{grid-area:2/3}'));
 assert(css.includes('env(safe-area-inset-right)')&&css.includes('env(safe-area-inset-bottom)'));
 assert(css.includes('min-height:48px')&&css.includes('focus-visible'));
 assert(css.includes('prefers-reduced-motion:reduce'));
 console.log('PASS V2 phase 11: responsive mobile/PC hints, safe-area hit targets, alert labels, hidden overlays');
})().catch(err=>{console.error(err);process.exitCode=1;});
