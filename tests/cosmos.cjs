const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ts=require('typescript');
const source=fs.readFileSync('src/experience/cosmos-config.ts','utf8');
const transpiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const exports={};vm.runInNewContext(transpiled,{exports,Date,Math,console});
assert.equal(exports.UNLOCK_AT,'2026-12-05T00:00:00-03:00');
const deadline=Date.parse(exports.UNLOCK_AT);
assert.equal(new Date(deadline).toISOString(),'2026-12-05T03:00:00.000Z');
assert.equal(exports.secondsUntil(deadline-2000),2);
assert.equal(exports.secondsUntil(deadline),0);
assert.equal(exports.secondsUntil(deadline+1000),0);
assert.equal(exports.countdownParts(90061).map(p=>p.value).join(','),'1,1,1,1');
assert.equal(exports.MEMORIES.length,6);
assert.equal(new Set(exports.MEMORIES.map(m=>m.id)).size,6);
assert(exports.MEMORIES.every(m=>Number.isFinite(m.x)&&Number.isFinite(m.y)&&Number.isFinite(m.z)&&m.title&&m.letter));
assert.equal(Object.keys(exports.PALETTES).length,3);
console.log('PASS: cosmos countdown Santiago, preview data, memories and palettes.');
