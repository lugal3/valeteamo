// Dependency-free sanity tests for the new deterministic house and geometry.
const assert=require('node:assert/strict');
(async()=>{
 const {createHouse,HEIGHT,stairHeight,groundHeight,blocked,lineBlocked,setDoor,setDrawer}=await import('../src/lab/world.js');
 const g=createHouse('ground'),u=createHouse('upstairs');
 assert.equal(g.spawn.y,0);assert.equal(u.spawn.y,HEIGHT);
 assert(g.boxes.length>60);assert(g.objects.length>12);
 assert.equal(stairHeight(9.75,9.15),0);assert(Math.abs(stairHeight(9.75,4.55)-HEIGHT)<.0001);
 assert.equal(stairHeight(5,8),null);assert.equal(groundHeight(6,3,HEIGHT),HEIGHT);
 assert(blocked(g.boxes,-.02,0,5),'outside west wall solid');
 assert(!blocked(g.boxes,6,0,8.4),'entry corridor passable');
 assert(!blocked(g.boxes,6,HEIGHT,3.8),'upstairs landing passable');
 const door=g.objects.find(o=>o.id==='salon');
 assert(door&&!door.open&&door.box.solid);
 const before=door.box.z;setDoor(door,true);assert(door.open&&!door.box.solid&&door.box.z!==before);
 setDoor(door,false);assert(door.box.solid&&door.box.z===before);
 const drawer=g.objects.find(o=>o.id==='drawer');const pos=drawer.box.z;
 setDrawer(drawer,true);assert(drawer.box.z>pos);setDrawer(drawer,false);assert(drawer.box.z===pos);
 assert(lineBlocked(g.boxes,{x:5.5,y:1.5,z:2},{x:9.5,y:1.5,z:2.5}),'wall blocks cross-room interaction');
 assert(!lineBlocked(g.boxes,{x:5.5,y:1.5,z:7},{x:6.5,y:1.5,z:7}),'hallway line of sight free');
 const ids=g.objects.map(o=>o.id);assert.equal(new Set(ids).size,ids.length);
 for(const b of g.boxes)for(const key of ['x','y','z','w','h','d'])assert(Number.isFinite(b[key]),b.id+': '+key);
 const {interactionTarget,canApproachDoor}=await import('../src/lab/interactions.js');
 const camera={x:0,y:1.63,z:0,yaw:0,pitch:0};
 const near={id:'near',kind:'note',x:.04,y:1.63,z:1.8},other={id:'other',kind:'note',x:-.04,y:1.63,z:1.8};
 const scene={boxes:[],objects:[near,other]};
 assert.equal(interactionTarget(scene,camera,other),other,'Small aim changes retain the current valid target');
 near.taken=true;other.taken=true;assert.equal(interactionTarget(scene,camera),null,'Collected objects disappear from picking');
 scene.objects=[{...near,taken:false,x:.5,z:2.43}];
 assert.equal(interactionTarget(scene,camera),null,'Reach uses actual distance, including lateral offset');
 scene.objects=[{...near,taken:false,x:0,z:1.8}];
 scene.boxes=[{id:'wall',x:0,y:1.5,z:.9,w:3,h:3,d:.12,solid:true}];
 assert.equal(interactionTarget(scene,camera,scene.objects[0]),null,'Hysteresis never keeps a target behind a wall');
 const testDoor={id:'test',kind:'door',open:false,x:0,y:1.1,z:.8};
 assert(canApproachDoor({boxes:[]},{x:0,y:0,z:0},testDoor));
 assert(!canApproachDoor(scene,{x:0,y:0,z:.2},{...testDoor,z:1.05}),'Automatic doors need line of sight');
 const plants=g.boxes.filter(b=>b.shape==='leaf');
 assert.equal(plants.length,28);assert(plants.every(b=>!b.solid),'Leaves have volume without blocking paths');
 const {rayDistance,lightDepthField,LIGHT_DEPTH_SIZE,LIGHT_REACH}=await import('../src/lab/lighting.js');
 const lightWall={id:'occluder',x:0,y:1.5,z:2,w:4,h:3,d:.2,solid:true};
 assert(Math.abs(rayDistance([lightWall],camera,{x:0,y:0,z:1})-1.9)<1e-6,'Light stops at the wall surface');
 assert.equal(rayDistance([{...lightWall,solid:false}],camera,{x:0,y:0,z:1}),LIGHT_REACH,'Decorative geometry does not shadow the torch');
 assert.equal(rayDistance([lightWall],camera,{x:0,y:0,z:-1}),LIGHT_REACH,'Geometry behind the light does not block its beam');
 const field=lightDepthField([lightWall],camera,[1,0,0],[0,1,0],[0,0,1]);
 assert.equal(field.length,LIGHT_DEPTH_SIZE*LIGHT_DEPTH_SIZE);
 const center=field[(LIGHT_DEPTH_SIZE/2)*LIGHT_DEPTH_SIZE+LIGHT_DEPTH_SIZE/2]/255*LIGHT_REACH;
 assert(center>=1.9&&center<2.05,'Small depth texture encodes actual obstruction distances');
 console.log('PASS: 3D layout, floors, stairs, collisions, occlusion, doors/drawer and deterministic content');
 console.log('PASS: stable contextual targets, actual reach, wall occlusion, automatic-door sight and nonblocking leaves');
})().catch(e=>{console.error(e);process.exitCode=1});
